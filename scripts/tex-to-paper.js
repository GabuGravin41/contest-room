// Converts the LaTeX problem paper into the built-in online paper.
//   npm run paper                       (reads paper/round1.tex)
//   node scripts/tex-to-paper.js paper/other.tex
// Writes lib/paper.js (the paper) and lib/key.js (Section A answers). Vercel runs this on every deploy.
// A paper uploaded on the admin page takes priority over this built-in one.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { basename } from 'node:path';
import { convert } from '../lib/tex.js';

const file = process.argv[2] || 'paper/round1.tex';
const instructionsFile = 'paper/instructions.txt';
const instructions = existsSync(instructionsFile)
  ? readFileSync(instructionsFile, 'utf8').split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('#'))
  : ['Answer all problems. Your answers save automatically.'];

const { paper, key, points, warnings, summary } = convert(readFileSync(file, 'utf8'), { instructions, id: basename(file, '.tex') });

const header = `// GENERATED from ${file} by scripts/tex-to-paper.js on ${new Date().toISOString()}.\n// Edit the .tex file (and paper/instructions.txt), then run \`npm run paper\`. Do not edit this file by hand.\n`;
writeFileSync('lib/paper.js', header + `export const PAPER = ${JSON.stringify(paper, null, 2)};

// Every answer field the server will accept, e.g. "1", "8a", "15".
export const answerKeysOf = p => new Set(p.sections.flatMap(s => s.problems.flatMap(q =>
  q.type === 'written' ? q.parts.map(pt => q.id + pt.id) : [q.id])));
export const ANSWER_KEYS = answerKeysOf(PAPER);
`);
writeFileSync('lib/key.js', header + `// Multiple-choice answer key, used only by scripts. Never sent to browsers.
export const MCQ_KEY = ${JSON.stringify(key)};
export const MCQ_POINTS = ${JSON.stringify(points)};
`);

console.log(`Paper: ${summary.title} · ${summary.round} · ${summary.problems} problems · ${summary.marks} marks · sections ${summary.sections}`);
console.log(summary.missingKey.length ? `Answer key: MISSING for problems ${summary.missingKey.join(', ')} (add the table inside \\ifanswers)` : `Answer key: ${summary.mcq} multiple-choice answers found`);
for (const w of warnings) console.log('Note: ignored ' + w);
